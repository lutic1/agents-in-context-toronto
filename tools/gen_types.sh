#!/usr/bin/env bash
# Regenerate web/lib/types.ts from the API's /openapi.json with openapi-typescript (AD-14).
# Never edit web/lib/types.ts by hand. B01's `gen:types` npm script calls this tool.
#
# Usage: tools/gen_types.sh            build the schema from the backend code (no server, no secrets)
#        DXP_OPENAPI_URL=<url> tools/gen_types.sh   read a running API's /openapi.json instead
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="$root/web/lib/types.ts"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

if [[ -n "${DXP_OPENAPI_URL:-}" ]]; then
  curl -fsS "$DXP_OPENAPI_URL" -o "$tmp/openapi.json"
else
  (cd "$root/backend" && uv run --quiet python -c \
    'import json, sys; from dxp.api.app import create_app; json.dump(create_app().openapi(), sys.stdout, indent=2, sort_keys=True)') \
    > "$tmp/openapi.json"
fi

mkdir -p "$(dirname "$out")"
npx --yes openapi-typescript@7.13.0 "$tmp/openapi.json" --output "$tmp/types.ts" >/dev/null
{
  echo "// Generated by tools/gen_types.sh from the API's /openapi.json. Do not edit by hand."
  cat "$tmp/types.ts"
} > "$out"
echo "wrote ${out#$root/}"
